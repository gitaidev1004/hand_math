# 1) 3x - 7 = 14
x1 = (14 + 7) / 3
print("1) x =", x1, " 검산:", 3 * x1 - 7)

# 2) 2(x-3) = 4x+2  ->  2x-6 = 4x+2  ->  -2x = 8
x2 = (2 + 6) / (2 - 4)
print("2) x =", x2, " 검산: 좌변", 2 * (x2 - 3), "우변", 4 * x2 + 2)

# 3) 5x + 2 - 3x + 7 = 2x + 9  (여러 값으로 확인)
for t in [-1, 0, 3]:
    a = 5 * t + 2 - 3 * t + 7
    b = 2 * t + 9
    print("3) x =", t, "원식", a, "정리식", b, a == b)

# 4), 5) 두 점을 지나는 직선
x_1, y_1 = 1, 5
x_2, y_2 = 4, 14
slope = (y_2 - y_1) / (x_2 - x_1)
intercept = y_1 - slope * x_1
print("4) 기울기 =", slope)
print("5) 절편 =", intercept, "-> y = {:.0f}x + {:.0f}".format(slope, intercept))

