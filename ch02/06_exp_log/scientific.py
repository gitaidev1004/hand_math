# 과학적 표기법
big = 7e9          # 7 x 10^9 = 70억
small = 1e-6       # 1 x 10^-6 = 0.000001

print("big   =", big)
print("small =", small)
print("일반 표기로:", "{:,.0f}".format(big))

# 거듭제곱 연산자 **
print("2 ** 10 =", 2 ** 10)
print("10 ** 3 =", 10 ** 3)
print("2 ** 0  =", 2 ** 0)
print("2 ** -1 =", 2 ** -1)

# 지수 법칙 확인
print("2**2 * 2**3 =", 2**2 * 2**3, " / 2**5 =", 2**5)
print("2**5 / 2**2 =", 2**5 / 2**2, " / 2**3 =", 2**3)
print("(2**2)**3   =", (2**2)**3, " / 2**6 =", 2**6)
