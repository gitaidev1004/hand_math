# 괄호가 없을 때와 있을 때를 비교한다
print("2 + 3 * 4      =", 2 + 3 * 4)        # 곱셈 먼저
print("(2 + 3) * 4    =", (2 + 3) * 4)      # 괄호 먼저

print("12 / 3 * 2     =", 12 / 3 * 2)       # 왼쪽부터
print("12 / (3 * 2)   =", 12 / (3 * 2))     # 괄호 먼저

print("10 - 4 + 2     =", 10 - 4 + 2)       # 왼쪽부터

# 그림 1-5의 식을 단계별로 확인
step1 = 8 - 6                 # 괄호
step2 = 3 * step1             # 곱셈
step3 = step2 / 2             # 나눗셈
step4 = 2 + step3             # 덧셈
print("단계별 결과:", step1, step2, step3, step4)
print("한 줄 계산  :", 2 + 3 * (8 - 6) / 2)
